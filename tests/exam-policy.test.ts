import assert from 'node:assert/strict'
import { certifications } from '../lib/catalog'
import { examPolicy, parseExamMinutes, PRACTICE_PASS_NOTE } from '../lib/exam-policy'
for (const cert of certifications) {
  const p = examPolicy(cert.id)
  assert.ok(p.passingScore.length > 20, cert.id)
  assert.ok(p.passingSource.startsWith('https://'), cert.id)
  assert.ok(p.durationMinutes === null || (p.durationMinutes > 0 && p.durationMinutes <= 480), cert.id)
  assert.equal(p.mockPassPercent, 70)
}
assert.equal(examPolicy('dp-700').durationMinutes, 100)
assert.equal(examPolicy('az-900').durationMinutes, 45)
assert.equal(examPolicy('aws-clf-c02').durationMinutes, 90)
assert.equal(examPolicy('aws-saa-c03').durationMinutes, 130)
assert.equal(examPolicy('isc2-certified-in-cybersecurity').durationMinutes, 120)
assert.equal(examPolicy('cisco-ccna').durationMinutes, 120)
assert.equal(examPolicy('isaca-cism').durationMinutes, 240)
assert.equal(examPolicy('comptia-cysa-plus').durationMinutes, 165)
assert.equal(examPolicy('comptia-a-plus').durationMinutes, 90)
assert.match(examPolicy('comptia-a-plus').durationNote, /two separate exams/)
assert.match(examPolicy('comptia-a-plus').passingScore, /675.*700/)
assert.match(examPolicy('cisco-ccna').passingScore, /Not publicly disclosed/)
assert.match(examPolicy('databricks-data-engineer-associate').passingScore, /Not publicly disclosed/)
assert.match(examPolicy('mos-word-expert-2019').passingScore, /varies by exam/)
assert.equal(examPolicy('aws-ai-business-strategist').durationMinutes, null)
assert.equal(examPolicy('unknown').mockPassPercent, null)
assert.equal(examPolicy('unknown').durationMinutes, null)
assert.match(PRACTICE_PASS_NOTE, /not the official passing score/)
assert.equal(parseExamMinutes('2 hours'), 120)
assert.equal(parseExamMinutes('Two hours'), 120)
assert.equal(parseExamMinutes('100 minutes'), 100)
assert.equal(parseExamMinutes('130–170 minutes'), null)
assert.equal(parseExamMinutes('2 separate exams'), null)
console.log(`Exam policies verified for ${certifications.length} certifications; scaled scores remain separate from practice percentages.`)
